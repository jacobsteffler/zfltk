//! Prints classes.zig: one opaque type per class in defs.zig, with the declarations
//! and methods of its whole parent chain aliased onto it.

const std = @import("std");
const defs = @import("defs.zig");

const names = @typeInfo(defs).@"struct".decl_names;
const reserved: []const []const u8 = &.{ "parent", "Options", "new", "apply", "Methods" };
const Probe = opaque {};

pub const output = blk: {
    @setEvalBranchQuota(100_000);
    var out: []const u8 =
        \\// Generated by `zig build gen` from defs.zig. Do not edit.
        \\
        \\const defs = @import("defs.zig");
        \\
    ;
    for (names) |name| out = out ++ class(name);
    break :blk out;
};

fn class(comptime name: []const u8) []const u8 {
    // Base first.
    var chain: []const []const u8 = &.{};
    var next: ?[]const u8 = name;
    while (next) |n| : (next = parentName(n)) chain = .{n} ++ chain;

    var out: []const u8 = "\npub const " ++ name ++ " = opaque {\n" ++
        "    pub const def = defs." ++ name ++ ";\n" ++
        "    pub const Options = def.Options;\n";
    for (chain, 0..) |owner, i| {
        var section: []const u8 = "";
        for (declNames(owner)) |decl| {
            if (overridden(decl, chain[i + 1 ..])) continue;
            section = section ++ "    pub const " ++ decl ++
                " = defs." ++ owner ++ "." ++ decl ++ ";\n";
        }
        for (methodNames(owner)) |method| {
            if (overridden(method, chain[i + 1 ..])) continue;
            section = section ++ "    pub const " ++ method ++
                " = defs." ++ owner ++ ".Methods(@This())." ++ method ++ ";\n";
        }
        if (section.len > 0) out = out ++ "\n" ++ section;
    }
    return out ++ "};\n";
}

fn parentName(comptime name: []const u8) ?[]const u8 {
    const def = @field(defs, name);
    if (!@hasDecl(def, "parent")) return null;
    for (names) |n| {
        if (@field(defs, n) == def.parent) return n;
    }
    @compileError("the parent of " ++ name ++ " is not listed in defs.zig");
}

/// The public declarations of a def that aren't part of the def protocol.
fn declNames(comptime name: []const u8) []const [:0]const u8 {
    var result: []const [:0]const u8 = &.{};
    decls: for (@typeInfo(@field(defs, name)).@"struct".decl_names) |decl| {
        for (reserved) |r| {
            if (std.mem.eql(u8, decl, r)) continue :decls;
        }
        result = result ++ .{decl};
    }
    return result;
}

fn methodNames(comptime name: []const u8) []const [:0]const u8 {
    const def = @field(defs, name);
    if (!@hasDecl(def, "Methods")) return &.{};
    return @typeInfo(def.Methods(Probe)).@"struct".decl_names;
}

fn overridden(comptime member: []const u8, comptime derived: []const []const u8) bool {
    for (derived) |name| {
        for (declNames(name) ++ methodNames(name)) |m| {
            if (std.mem.eql(u8, m, member)) return true;
        }
    }
    return false;
}

pub fn main(init: std.process.Init) !void {
    try std.Io.File.stdout().writeStreamingAll(init.io, output);
}

test "classes.zig is up to date (run `zig build gen`)" {
    try std.testing.expectEqualStrings(output, @embedFile("classes.zig"));
}
